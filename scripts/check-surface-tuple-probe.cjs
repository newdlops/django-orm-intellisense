'use strict';
const assert = require('node:assert/strict');
const { compact, encodeTable, decodeTable } = require('./probe-surface-tuple-cost.cjs');
for (const mode of ['json-key', 'nested-map']) {
  const source = JSON.parse('{"app.Post":{"instance":{"title":["scalar",null,"field","CharField"],"__proto__":["scalar",null,"field","CharField"]},"manager":{"first":["instance","app.Post","method",null]},"queryset":{"first":["instance","app.Post","method",null]}},"app.Other":{"manager":{"first":["instance","app.Post","method",null]}}}');
  const wire = JSON.stringify(source);
  const result = compact(source, mode);
  assert.equal(JSON.stringify(source), wire);
  assert.equal(JSON.stringify(result), wire);
  assert.notEqual(result, source);
  assert.notEqual(result['app.Post'], source['app.Post']);
  assert.notEqual(result['app.Post'].instance, source['app.Post'].instance);
  assert.equal(result['app.Post'].manager.first, result['app.Post'].queryset.first);
  assert.notEqual(result['app.Post'].manager.first, result['app.Other'].manager.first);
  assert.equal(result['app.Post'].instance.title, result['app.Post'].instance.__proto__);
  assert.equal(Object.getPrototypeOf(result['app.Post'].instance), Object.prototype);
  assert.ok(Object.isFrozen(result['app.Post'].manager.first));
  assert.throws(() => { result['app.Post'].manager.first[1] = 'app.Wrong'; }, TypeError);
  source['app.Post'].manager.first[1] = 'app.New';
  source['app.Post'].instance.title[3] = 'DateField';
  delete source['app.Post'].queryset.first;
  assert.equal(JSON.stringify(result), wire);
  const next = compact(source, mode);
  assert.equal(next['app.Post'].manager.first[1], 'app.New');
  assert.equal(next['app.Post'].instance.title[3], 'DateField');
  assert.equal(next['app.Post'].queryset.first, undefined);
  result['app.Post'].instance.added = ['scalar', null, 'field', 'IntegerField'];
  assert.equal(source['app.Post'].instance.added, undefined);
  const odd = JSON.parse('{"app.Odd":{"instance":{"two":["scalar",null],"three":["scalar",null,"field"],"four":["scalar",null,"field",null],"extra":["scalar",null,"field",null,"future"],"number":["scalar",3]}}}');
  const owned = compact(odd, mode);
  assert.deepEqual(owned, odd);
  assert.notEqual(owned['app.Odd'].instance.two, owned['app.Odd'].instance.three);
  assert.notEqual(owned['app.Odd'].instance.three, owned['app.Odd'].instance.four);
  assert.equal(owned['app.Odd'].instance.extra, odd['app.Odd'].instance.extra);
  assert.equal(owned['app.Odd'].instance.number, odd['app.Odd'].instance.number);
  const original = JSON.parse(wire);
  const encoded = encodeTable(original);
  const decoded = decodeTable(JSON.stringify({ surfaceIndex: encoded }));
  assert.equal(JSON.stringify(decoded.surfaceIndex), wire);
  assert.equal(JSON.stringify(original), wire);
  assert.ok(Object.isFrozen(decoded.surfaceIndex['app.Post'].manager.first));
}
console.log('Candidate-only ownership, frozen aliases, per-model/generation isolation, tuple length/null, unusual keys and complete wire roundtrip checks passed. No production integration claim.');
